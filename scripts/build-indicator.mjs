// Package the authored CSS indicators as one dependency-free browser module.
import { mkdir, readFile, writeFile } from "node:fs/promises";

const base = new URL("../", import.meta.url);
const source = await readFile(new URL("specimens/app.js", base), "utf8");
const stylesheet = (await readFile(new URL("specimens/styles.css", base), "utf8")).replace(/\/\*[\s\S]*?\*\//g, "");
const families = [
  ["orbit", "Orbit", "OrbitIndicator", "ORBIT", "orbit-"],
  ["beacon", "Bars", "BeaconIndicator", "BEACON", "beacon-"],
  ["matrix", "Matrix", "MatrixIndicator", "MATRIX", "matrix-"],
  ["cells", "Merge", "CellIndicator", "CELL", "cell-"],
  ["register", "Encode", "RegisterIndicator", "REGISTER", "register-"],
  ["bands", "Scan", "BandIndicator", "BAND", "band-"],
  ["lift", "Lift", "LiftQueueIndicator", "LIFT_QUEUE", "lift-queue-"]
];
const prefixes = families.map((family) => family[4]);
const classRoots = ["orbit-indicator", "orbit-node", "orbit-dot", "beacon-indicator", "matrix-indicator", "cell-indicator", "register-indicator", "band-indicator", "lift-queue-indicator"];
function splitSelectors(selector) {
  const selectors = [];
  let depth = 0, start = 0;
  for (let index = 0; index < selector.length; index++) {
    if (selector[index] === "(" || selector[index] === "[") depth++;
    if (selector[index] === ")" || selector[index] === "]") depth--;
    if (selector[index] === "," && depth === 0) {
      selectors.push(selector.slice(start, index).trim());
      start = index + 1;
    }
  }
  selectors.push(selector.slice(start).trim());
  return selectors;
}
const css = [];
let cursor = 0;
while (cursor < stylesheet.length) {
  const open = stylesheet.indexOf("{", cursor);
  if (open < 0) break;
  const selector = stylesheet.slice(cursor, open).trim();
  let depth = 1, end = open + 1, quote = "";
  for (; end < stylesheet.length && depth; end++) {
    const char = stylesheet[end];
    if (char === "\\") { end++; continue; }
    if (quote) { if (char === quote) quote = ""; continue; }
    if (char === '"' || char === "'") { quote = char; continue; }
    if (char === "{") depth++;
    if (char === "}") depth--;
  }
  const body = stylesheet.slice(open, end);
  if (selector.startsWith("@keyframes ")) {
    if (prefixes.some((prefix) => selector.slice(11).startsWith(prefix))) css.push(selector + " " + body);
  } else if (!selector.startsWith("@")) {
    const owned = splitSelectors(selector).filter((part) => {
      const name = part.match(/^\.([\w-]+)/)?.[1];
      return name && classRoots.some((root) => name === root || name.startsWith(root + "__"));
    });
    if (owned.length) css.push(owned.join(",\n") + " " + body);
  }
  cursor = end;
}

const definitions = families.map(([, , factory, constant]) => {
  const config = source.match(new RegExp(`^const ${constant}_VARIANTS = Object.freeze\\([\\s\\S]*?^\\}\\);`, "m"))?.[0];
  const fn = source.match(new RegExp(`^function ${factory}\\([\\s\\S]*?^\\}`, "m"))?.[0];
  if (!config || !fn) throw new Error(`Missing indicator source: ${factory}`);
  return config + "\n\n" + fn;
}).join("\n\n");
const runtime = await readFile(new URL("components/indicator-element.js", base), "utf8");
const license = await readFile(new URL("LICENSE", base), "utf8");
const helpers = `const createElement = (tag, className) => Object.assign(document.createElement(tag), { className });`;
const registry = `export const loadingAnimations = Object.freeze(${JSON.stringify(families.map(([id, label]) => ({ id, label })))});\nconst factories = {${families.map(([id, , fn]) => `${id}: ${fn}`).join(", ")}};`;
await writeFile(new URL("indicator.js", base), `/* Generated by scripts/build-indicator.mjs.\n${license}\n*/\n\n${helpers}\n\n${definitions}\n\nconst indicatorCSS = ${JSON.stringify(css.join("\n\n"))};\n\n${registry}\n\n${runtime}`);
console.log(`Built indicator.js with ${families.length} original animations and ${css.length} CSS rules.`);

// The CLI installs the same runtime the playground uses, plus a typed React adapter.
const files = await Promise.all([
  ["components/loading.tsx", "loading.tsx", "registry:ui"],
  ["indicator.js", "loading-indicator.js", "registry:file"],
  ["components/loading-indicator.d.ts", "loading-indicator.d.ts", "registry:file"],
].map(async ([path, name, type]) => ({
  path, type, target: `@ui/${name}`, content: await readFile(new URL(path, base), "utf8"),
})));
await mkdir(new URL("r/", base), { recursive: true });
await writeFile(new URL("r/loading.json", base), JSON.stringify({
  $schema: "https://ui.shadcn.com/schema/registry-item.json",
  name: "loading",
  type: "registry:ui",
  title: "Loading",
  description: "Seven animated loaders with size, speed and pause controls.",
  author: "Dani Asyrofi",
  files,
}, null, 2) + "\n");
console.log("Built r/loading.json with the React component, browser runtime and types.");
